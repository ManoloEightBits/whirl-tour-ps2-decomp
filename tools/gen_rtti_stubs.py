#!/usr/bin/env python3
"""Generate one probe source per single-inheritance RTTI class, to match its __tf function.

Usage: gen_rtti_stubs.py --slus <SLUS_204.89>

Writes src/rtti/<Class>.cpp. Each file declares the class and its base (the base's destructor is
out of line, so the base's __tf is a call, as in the game) and defines the constructor so the
compiler emits the vtable and the class's __tf. Only the __tf is compared with the game; the
constructor and destructor the compiler adds are listed in config/probes.txt, which verify.py
ignores. Output depends only on names and hierarchy read from the executable, no game code.
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import extract_rtti as e

ROOT = Path(__file__).resolve().parent.parent
HAND_WRITTEN = {'CollFilt', 'IVP_Collision_Filter', 'AI_AttackType', 'IVP_Actuator', 'IVP_U_Active_Value', 'Pickup', 'FEScreen', 'FEQuitScreen', 'FEStartScreen', 'FETrickScreen', 'IVP_Listener_Object', 'DD_Event_Listener', 'IVP_Listener_Collision', 'MBCL', 'ScootCL', 'MarActCL', 'DD_Collision_Listener', 'LunActCL', 'AI_PedestrianCL', 'IVP_Listener_Phantom', 'Global_Phantom_Listener', 'IVP_Controller', 'IVP_Controller_Independent', 'IP_PosCtrl', 'MotionCtrl', 'IP_RotCtrl', 'IP_AnimCtrl', 'MBCtrl', 'ScootCtrl'}

# Entries of config/probes.txt that do not come from a generated stub. The file is rewritten from
# scratch on every run, so anything verify.py must ignore for another reason has to be listed here.
MANUAL_PROBES = {
    '__13AI_AttackType': 'probe constructor in src/game/AI_AttackType.cpp',
    'Update__6Pickupf': 'placeholder in src/game/KeyPickup.cpp until Pickup::Update (0x0011B3D8) is decompiled',
}


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--slus', required=True)
    args = ap.parse_args()
    d = Path(args.slus).read_bytes()
    text = d[e.TEXT_OFFSET:e.TEXT_OFFSET + e.TEXT_SIZE]
    ro = d[e.RODATA_OFFSET:e.RODATA_OFFSET + e.RODATA_SIZE]
    tfs = e.find_tf_functions(text, e.find_rtti_strings(ro)).values()
    vts = e.find_vtables(ro, {t['tf_addr']: t for t in tfs})
    out = ROOT / 'src' / 'rtti'
    out.mkdir(parents=True, exist_ok=True)
    probes, done = list(MANUAL_PROBES), set()
    for v in sorted(vts, key=lambda v: v['vtable_addr']):
        name = v['class_name']
        if name in done or name in HAND_WRITTEN or not re.fullmatch(r'[A-Za-z]\w*', name) or re.match(r't\d', name) or len(v['bases']) > 1:
            continue
        # A 0x20-byte frame is the single-inheritance shape; bigger frames mean several bases.
        first_word = int.from_bytes(text[v['tf_addr'] - e.TEXT_BASE:][:4], 'little')
        # The last call must be __rtti_si (one polymorphic base) or __rtti_user (none).
        tf = next(t for t in tfs if t['tf_addr'] == v['tf_addr'])
        if first_word != 0x27BDFFE0 or tf['jals'][-1] not in (0x22CFF0, 0x22D010):
            continue
        done.add(name)
        base = v['bases'][0] if v['bases'] else None
        lines = ['// Generated by tools/gen_rtti_stubs.py: matches %s only.' % v['tf_symbol'], '']
        if base:
            lines += ['class %s\n{\npublic:\n    virtual ~%s();\n};\n' % (base, base),
                      'class %s : public %s\n{\npublic:\n    %s();\n};\n' % (name, base, name)]
        else:
            # No base: the destructor is the first out-of-line virtual, so defining it emits the vtable.
            lines += ['class %s\n{\npublic:\n    virtual ~%s();\n};\n' % (name, name)]
        lines += ['%s::%s%s()\n{\n}\n' % (name, '' if base else '~', name)]
        (out / (name + '.cpp')).write_text('\n'.join(lines))
        probes.append('__%d%s' % (len(name), name))
        probes.append('_$_%d%s' % (len(name), name))
    (ROOT / 'config' / 'probes.txt').write_text(
        '# Functions the compiler emits for tools/gen_rtti_stubs.py probes. They are not game code\n'
        '# and verify.py skips them.\n' + '\n'.join(sorted(set(probes))) + '\n')
    print('wrote %d probe sources' % len(done))


if __name__ == '__main__':
    sys.exit(main())
